/* 
--------------------------------------------------------------------------------
- Customer Analysis
--------------------------------------------------------------------------------

-- 1. Customer Order Activity
- First, find out how many orders each customers has placed?
*/

select customer_id, count(order_id) as total_orders
from orders
group by customer_id
order by total_orders desc;

/*
- 2. Customer Spending Analysis
- how much each customer has spent?
*/
select customer_id, sum(order_value) as total_spend
from orders
group by customer_id
order by total_spend desc;

/*
- 3. Average Order Value per Customer
- the average amount spent per order by each customer.
 */

select customer_id, round(avg(order_value),2) as average_order_value
from orders
group by customer_id
order by average_order_value desc;

/* 
-- 4. Customer Order Status Analysis
-- customer’s orders are distributed by status.
*/

select
customer_id,
sum(order_status = 'Delivered') as delivered_orders,
sum(order_status = 'Cancelled') as cancelled_orders,
sum(order_status = 'Refunded') as refunded_orders
from orders
group by customer_id
order by cancelled_orders desc;

/* 
-- 5. Customer Revenue Contribution
-- What percentage of total revenue comes from each customer.
*/

select
customer_id, sum(order_value) as total_spend,
round(sum(order_value)* 100.0 / sum(sum(order_value)) over (),2) as revenue_contribution_percentage
from orders
group by customer_id
order by revenue_contribution_percentage desc;

