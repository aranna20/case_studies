/*
-- Delivery Time by Category
-- Classify deliveries into Fast, Moderate, and Slow based on delivery time.
*/
select
	case
	when delivery_time_min <= 30 then 'Fast'
	when delivery_time_min <= 60 then 'Moderate'
	else 'Slow'
	end as delivery_time_category,
count(*) as total_orders
from orders
group by
	case
	when delivery_time_min <= 30 then 'Fast'
	when delivery_time_min <= 60 then 'Moderate'
	else 'Slow'
end
order by total_orders desc;

/*
-- Average Delivery Time by Distance Category
-- Compare delivery time across Short, Medium, and Long distance categories.

*/

select
case
	when delivery_distance_km <= 5 then 'Short'
	when delivery_distance_km <= 10 then 'Medium'
	else 'Long'
	end as distance_category,
count(*) as total_orders,
round(avg(delivery_time_min), 2) as average_delivery_time
from orders
group by
	case
	when delivery_distance_km <= 5 then 'Short'
	when delivery_distance_km <= 10 then 'Medium'
	else 'Long'
end
order by average_delivery_time;

